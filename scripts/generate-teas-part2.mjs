const inf = (seconds, notes = {}) =>
  seconds.map((s, i) => ({
    n: i + 1,
    seconds: s,
    ...(notes[i] ? { notes: notes[i] } : {}),
  }));

const brew = ({ vessel, ratio, temp, gongfu, westernGrams = 3, westernVol = 250, westernTemp, western, cold }) => ({
  gongfu: {
    vessel,
    ratio,
    waterTemp: temp,
    infusions: inf(...(Array.isArray(gongfu) ? [gongfu] : [gongfu.times, gongfu.notes])),
  },
  western: {
    grams: westernGrams,
    volume: westernVol,
    waterTemp: westernTemp ?? temp,
    infusions: inf(...(Array.isArray(western) ? [western] : [western.times, western.notes])),
  },
  ...(cold ? { coldBrew: cold } : {}),
});

